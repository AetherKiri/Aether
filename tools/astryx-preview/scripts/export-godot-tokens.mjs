import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const require = createRequire(import.meta.url);
const css = readFileSync(
  require.resolve("@astryxdesign/theme-neutral/theme.css"),
  "utf8",
);
// Neutral inherits some overlay tokens from core instead of redefining them.
const defaults = readFileSync(
  resolve(
    dirname(require.resolve("@astryxdesign/core/theme")),
    "tokens.stylex.js",
  ),
  "utf8",
);
const roles = {
  canvas: "color-background-body",
  surface: "color-background-surface",
  subtle: "color-neutral",
  selected: "color-accent-muted",
  text: "color-text-primary",
  secondary: "color-text-secondary",
  disabled: "color-text-disabled",
  border: "color-border",
  input_border: "color-border-emphasized",
  accent: "color-accent",
  on_accent: "color-on-accent",
  toast_surface: "color-background-inverted",
  focus: "color-info",
  danger: "color-error",
  danger_muted: "color-error-muted",
  on_danger_muted: "color-on-error-muted",
};
const tokens = { light: {}, dark: {} };
for (const [key, role] of Object.entries(roles)) {
  const pattern = new RegExp(
    `--${role}['"]?:\\s*['"]?light-dark\\((#[0-9a-fA-F]+),\\s*(#[0-9a-fA-F]+)\\)`,
  );
  const value = css.match(pattern) ?? defaults.match(pattern);
  if (!value) throw new Error(`Missing Neutral token: ${role}`);
  tokens.light[key] = value[1];
  tokens.dark[key] = value[2];
}
// Composition dimensions match the React layouts; native touch targets are 44 pt.
tokens.layout = {
  phone_breakpoint: 700,
  rail_width: 48,
  settings_nav_width: 208,
  phone_gutter: 20,
  tablet_gutter: 24,
  page_radius: 28,
  control_radius: 10,
  card_radius: 12,
  control_height: 44,
  bottom_nav_height: 48,
  fast_seconds: 0.125,
  page_seconds: 0.225,
};
const target = new URL(
  "../../../apps/godot_app/assets/ui/astryx/tokens.json",
  import.meta.url,
);
writeFileSync(target, JSON.stringify(tokens, null, 2) + "\n");
// A preloaded script travels with every Godot export without broadening filters.
writeFileSync(
  new URL("tokens.gd", target),
  "# Generated by tools/astryx-preview/scripts/export-godot-tokens.mjs.\n" +
    "# Astryx Neutral (MIT); see ASTRYX-LICENSE and res://legal/astryx.txt.\n" +
    "extends RefCounted\n\nconst VALUES := " +
    JSON.stringify(tokens, null, 4) +
    "\n",
);
console.log("Exported Neutral light/dark tokens to Godot.");
