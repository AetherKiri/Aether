#!/usr/bin/env python3
"""Translate the host's reference compute kernels into standalone Metal source.

This intentionally supports only the nine named kernels, not arbitrary GLSL.
Metal resources are context members; integer blend arithmetic remains verbatim.
The generated header is checked in; Apple builds do not need Godot or Python.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
NAMES = ('Blend', 'AlphaConvert', 'AlphaBlendA', 'Blend2', 'Blend3',
         'CopyTriangles', 'DrawTriangles', 'DrawMaskedTriangles', 'Mosaic')


def generate():
    reference = (ROOT / 'bridge/godot_extension/src/aether_runtime_player.cpp').read_text()
    parts = ['''// Generated by tools/generate_apple_metal_shaders.py. Do not edit.
// Reference: bridge/godot_extension/src/aether_runtime_player.cpp compute kernels.
#pragma once
static const char *kAppleMetalBridgeShaders = R"MSL(
#include <metal_stdlib>
using namespace metal;
using vec2 = float2; using vec3 = float3; using vec4 = float4;
using ivec2 = int2; using ivec3 = int3; using ivec4 = int4;
using uvec2 = uint2; using uvec3 = uint3; using uvec4 = uint4;
template<access A> float4 imageLoad(texture2d<float, A> t, int2 p) { return t.read(uint2(p)); }
void imageStore(texture2d<float, access::read_write> t, int2 p, float4 c) { t.write(c, uint2(p)); }
template<access A> int2 imageSize(texture2d<float, A> t) { return int2(t.get_width(), t.get_height()); }
bool2 lessThan(float2 a, float2 b) { return a < b; }
bool2 greaterThan(float2 a, float2 b) { return a > b; }
''']
    for name in NAMES:
        match = re.search(r'bool Ensure' + name + r'Pipeline\(.*?R"GLSL\((.*?)\)GLSL', reference, re.S)
        if not match:
            raise ValueError(f'missing reference kernel {name}')
        source = match[1]
        params = re.search(r'uniform Params \{(.*?)\} pc;', source, re.S)
        textures = re.findall(r'layout\(rgba8, set = 0, binding = (\d+)\) uniform (readonly )?image2D (\w+);', source)
        members, arguments, values = ['uint3 gl_GlobalInvocationID;', f'{name}Params pc;'], [], ['gid', 'pc']
        for binding, readonly, label in textures:
            access = 'read' if readonly else 'read_write'
            typename = f'texture2d<float, access::{access}>'
            members.append(f'{typename} {label};')
            arguments.append(f'{typename} {label} [[texture({binding})]]')
            values.append(label)
        buffer = re.search(r'readonly buffer (\w+) \{\s*(vec4|float) \w+\[\];\s*\} (\w+);', source)
        if buffer:
            _, typename, label = buffer.groups()
            members.append(f'device const {typename} *{label};')
            arguments.append(f'device const {typename} *{label} [[buffer(0)]]')
            values.append(label)
        body = source[params.end():]
        body = body.replace('void main()', 'void run()')
        body = re.sub(r'\bvertex\b', 'vertex_index', body)
        body = re.sub(r'\b(vertices|rects)\.(vertex|vertex_index|value)\[', r'\1[', body)
        parts.append(f'struct {name}Params {{{params[1]}}};\n')
        parts.append(f'struct {name}Context {{\n' + '\n'.join(members) + '\n' + body + '\n};\n')
        arguments += [f'constant {name}Params &pc [[buffer(1)]]', 'uint3 gid [[thread_position_in_grid]]']
        parts.append(f'kernel void apple_{name}(' + ',\n'.join(arguments) + ') {\n')
        parts.append(f'    {name}Context context = {{' + ', '.join(values) + '};\n    context.run();\n}\n')
    parts.append(')MSL";\n')
    return ''.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'apps/apple_host/HostKit/MetalBridgeShaders.h'
    output = generate()
    if args.check:
        if not path.exists() or path.read_text() != output:
            parser.exit(1, 'Metal shader header differs from its reference kernels; regenerate it.\n')
        print('PASS: generated Metal shader header matches reference kernels')
    else:
        path.write_text(output)


if __name__ == '__main__':
    main()
